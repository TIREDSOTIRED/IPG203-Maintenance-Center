namespace مركز_صيانة_الأجهزة;

/// <summary>
/// التفويض المستخدم لإرسال إشعار عند حدوث تغيير مهم في حالة الصيانة.
/// </summary>
public delegate void مفوض_إشعار_الصيانة(
    جهاز_منزلي الجهاز,
    حالة_الصيانة الحالة_السابقة,
    حالة_الصيانة الحالة_الجديدة,
    string الرسالة);

/// <summary>
/// الصنف المجرد الذي يجمع البيانات والعمليات المشتركة للأجهزة المنزلية.
/// </summary>
public abstract class جهاز_منزلي : Iعمليات_الجهاز
{
    private readonly string _الرقم_التسلسلي;
    private readonly DateTime _تاريخ_الاستلام;
    private readonly DateTime _تاريخ_التسليم_المتوقع;
    private readonly string _اسم_العميل;
    private readonly string _رقم_الهاتف;
    private readonly string _وصف_العطل;
    private readonly decimal _تكلفة_قطع_الغيار;
    private readonly decimal _أجور_العمل;
    private حالة_الصيانة _الحالة;

    protected جهاز_منزلي(
        string الرقم_التسلسلي,
        string اسم_العميل,
        string رقم_الهاتف,
        string وصف_العطل,
        decimal تكلفة_قطع_الغيار,
        decimal أجور_العمل,
        DateTime تاريخ_الاستلام,
        DateTime تاريخ_التسليم_المتوقع,
        حالة_الصيانة الحالة_المبدئية = حالة_الصيانة.مستلم)
    {
        _الرقم_التسلسلي = مدقق_البيانات.تحقق_من_الرقم_التسلسلي(الرقم_التسلسلي);
        _اسم_العميل = مدقق_البيانات.تحقق_من_النص(اسم_العميل, "اسم العميل");
        _رقم_الهاتف = مدقق_البيانات.تحقق_من_الهاتف(رقم_الهاتف);
        _وصف_العطل = مدقق_البيانات.تحقق_من_النص(وصف_العطل, "وصف العطل");
        _تكلفة_قطع_الغيار = مدقق_البيانات.تحقق_من_التكلفة(تكلفة_قطع_الغيار, "تكلفة قطع الغيار");
        _أجور_العمل = مدقق_البيانات.تحقق_من_التكلفة(أجور_العمل, "أجور العمل");
        مدقق_البيانات.تحقق_من_التواريخ(تاريخ_الاستلام, تاريخ_التسليم_المتوقع);
        مدقق_البيانات.تحقق_من_الحالة(الحالة_المبدئية);

        _تاريخ_الاستلام = تاريخ_الاستلام.Date;
        _تاريخ_التسليم_المتوقع = تاريخ_التسليم_المتوقع.Date;
        _الحالة = الحالة_المبدئية;
    }

    public string الرقم_التسلسلي => _الرقم_التسلسلي;
    public string اسم_العميل => _اسم_العميل;
    public string رقم_الهاتف => _رقم_الهاتف;
    public string وصف_العطل => _وصف_العطل;
    public decimal تكلفة_قطع_الغيار => _تكلفة_قطع_الغيار;
    public decimal أجور_العمل => _أجور_العمل;
    public DateTime تاريخ_الاستلام => _تاريخ_الاستلام;
    public DateTime تاريخ_التسليم_المتوقع => _تاريخ_التسليم_المتوقع;
    public حالة_الصيانة الحالة => _الحالة;

    public abstract string نوع_الجهاز { get; }
    public abstract decimal التكلفة_الإضافية { get; }

    /// <summary>
    /// الحدث الذي يعلن عن اكتمال الإصلاح أو تأخر التسليم.
    /// </summary>
    public event مفوض_إشعار_الصيانة? حدث_الصيانة;

    protected decimal التكلفة_الأساسية => _تكلفة_قطع_الغيار + _أجور_العمل;

    public abstract decimal حساب_تكلفة_الإصلاح();

    public void تحديث_الحالة(حالة_الصيانة الحالة_الجديدة)
    {
        مدقق_البيانات.تحقق_من_الحالة(الحالة_الجديدة);

        if (_الحالة == الحالة_الجديدة)
            return;

        if (!الانتقال_مسموح(_الحالة, الحالة_الجديدة))
            throw new InvalidOperationException($"لا يمكن نقل الجهاز من الحالة «{_الحالة}» إلى «{الحالة_الجديدة}».");

        حالة_الصيانة الحالة_السابقة = _الحالة;
        _الحالة = الحالة_الجديدة;

        if (الحالة_الجديدة == حالة_الصيانة.جاهز_للتسليم)
        {
            حدث_الصيانة?.Invoke(this, الحالة_السابقة, الحالة_الجديدة,
                $"اكتمل إصلاح الجهاز {الرقم_التسلسلي} ({نوع_الجهاز}) وأصبح جاهزاً للتسليم.");
        }
        else if (الحالة_الجديدة == حالة_الصيانة.متأخر)
        {
            حدث_الصيانة?.Invoke(this, الحالة_السابقة, الحالة_الجديدة,
                $"تنبيه تأخير: تجاوز الجهاز {الرقم_التسلسلي} موعد التسليم المتوقع.");
        }
    }

    public void عرض_البيانات()
    {
        Console.WriteLine("----------------------------------------------");
        Console.WriteLine($"نوع الجهاز: {نوع_الجهاز}");
        Console.WriteLine($"الرقم التسلسلي: {الرقم_التسلسلي}");
        Console.WriteLine($"اسم العميل: {اسم_العميل}");
        Console.WriteLine($"رقم الهاتف: {رقم_الهاتف}");
        Console.WriteLine($"وصف العطل: {وصف_العطل}");
        Console.WriteLine($"الحالة: {الحالة}");
        Console.WriteLine($"تاريخ الاستلام: {تاريخ_الاستلام:yyyy-MM-dd}");
        Console.WriteLine($"موعد التسليم المتوقع: {تاريخ_التسليم_المتوقع:yyyy-MM-dd}");
        Console.WriteLine($"تكلفة قطع الغيار: {تكلفة_قطع_الغيار:N2}");
        Console.WriteLine($"أجور العمل: {أجور_العمل:N2}");
        Console.WriteLine($"التكلفة الإضافية الخاصة بالجهاز: {التكلفة_الإضافية:N2}");
        Console.WriteLine($"إجمالي تكلفة الإصلاح: {حساب_تكلفة_الإصلاح():N2} وحدة نقدية");
        Console.WriteLine("----------------------------------------------");
    }

    private static bool الانتقال_مسموح(حالة_الصيانة الحالية, حالة_الصيانة الجديدة)
    {
        return الحالية switch
        {
            حالة_الصيانة.مستلم => الجديدة is حالة_الصيانة.قيد_الفحص or حالة_الصيانة.قيد_الإصلاح or حالة_الصيانة.متأخر,
            حالة_الصيانة.قيد_الفحص => الجديدة is حالة_الصيانة.قيد_الإصلاح or حالة_الصيانة.جاهز_للتسليم or حالة_الصيانة.متأخر,
            حالة_الصيانة.قيد_الإصلاح => الجديدة is حالة_الصيانة.جاهز_للتسليم or حالة_الصيانة.متأخر,
            حالة_الصيانة.جاهز_للتسليم => الجديدة is حالة_الصيانة.تم_التسليم or حالة_الصيانة.متأخر,
            حالة_الصيانة.متأخر => الجديدة is حالة_الصيانة.قيد_الإصلاح or حالة_الصيانة.جاهز_للتسليم or حالة_الصيانة.تم_التسليم,
            حالة_الصيانة.تم_التسليم => false,
            _ => false
        };
    }
}
