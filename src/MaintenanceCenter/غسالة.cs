namespace مركز_صيانة_الأجهزة;

/// <summary>
/// يمثل الغسالة ويضيف تكلفة أعمال المحرك إلى التكلفة الأساسية.
/// </summary>
public sealed class غسالة : جهاز_منزلي
{
    private readonly decimal _تكلفة_المحرك;

    public غسالة(
        string الرقم_التسلسلي, string اسم_العميل, string رقم_الهاتف, string وصف_العطل,
        decimal تكلفة_قطع_الغيار, decimal أجور_العمل, decimal تكلفة_المحرك,
        DateTime تاريخ_الاستلام, DateTime تاريخ_التسليم_المتوقع,
        حالة_الصيانة الحالة_المبدئية = حالة_الصيانة.مستلم)
        : base(الرقم_التسلسلي, اسم_العميل, رقم_الهاتف, وصف_العطل,
               تكلفة_قطع_الغيار, أجور_العمل, تاريخ_الاستلام, تاريخ_التسليم_المتوقع, الحالة_المبدئية)
    {
        _تكلفة_المحرك = مدقق_البيانات.تحقق_من_التكلفة(تكلفة_المحرك, "تكلفة المحرك");
    }

    public override string نوع_الجهاز => "غسالة";
    public decimal تكلفة_المحرك => _تكلفة_المحرك;
    public override decimal التكلفة_الإضافية => _تكلفة_المحرك;
    public override decimal حساب_تكلفة_الإصلاح() => decimal.Round(التكلفة_الأساسية + _تكلفة_المحرك, 2);
}
