namespace مركز_صيانة_الأجهزة;

/// <summary>
/// يدير أجهزة المركز، ويتابع الإحصائيات، ويستقبل أحداث تغيّر حالة الصيانة.
/// </summary>
public sealed class مركز_الصيانة
{
    private readonly List<جهاز_منزلي> _الأجهزة = new();
    private static readonly List<جهاز_منزلي> _السجل_المشترك = new();
    private static readonly object _قفل_السجل = new();

    public event Action<string>? تنبيه_الصيانة;

    public IReadOnlyList<جهاز_منزلي> الأجهزة => _الأجهزة.AsReadOnly();

    public static int عدد_الأجهزة_المسجلة
    {
        get
        {
            lock (_قفل_السجل)
                return _السجل_المشترك.Count;
        }
    }

    public static int عدد_الأجهزة_قيد_الإصلاح
    {
        get
        {
            lock (_قفل_السجل)
                return _السجل_المشترك.Count(جهاز => جهاز.الحالة == حالة_الصيانة.قيد_الإصلاح);
        }
    }

    public static decimal إجمالي_تكاليف_الإصلاحات
    {
        get
        {
            lock (_قفل_السجل)
                return _السجل_المشترك.Sum(جهاز => جهاز.حساب_تكلفة_الإصلاح());
        }
    }

    public void إضافة_جهاز(جهاز_منزلي الجهاز)
    {
        ArgumentNullException.ThrowIfNull(الجهاز);

        if (_الأجهزة.Any(موجود => string.Equals(موجود.الرقم_التسلسلي, الجهاز.الرقم_التسلسلي, StringComparison.OrdinalIgnoreCase)))
            throw new InvalidOperationException("يوجد جهاز مسجل مسبقاً بهذا الرقم التسلسلي.");

        lock (_قفل_السجل)
        {
            if (_السجل_المشترك.Any(موجود => string.Equals(موجود.الرقم_التسلسلي, الجهاز.الرقم_التسلسلي, StringComparison.OrdinalIgnoreCase)))
                throw new InvalidOperationException("الرقم التسلسلي مستخدم في سجل المركز بالفعل.");

            _السجل_المشترك.Add(الجهاز);
        }

        _الأجهزة.Add(الجهاز);
        الجهاز.حدث_الصيانة += عند_تغير_حالة_الصيانة;
    }

    public جهاز_منزلي? البحث_عن_جهاز(string الرقم_التسلسلي)
    {
        string قيمة = مدقق_البيانات.تحقق_من_النص(الرقم_التسلسلي, "الرقم التسلسلي");
        return _الأجهزة.FirstOrDefault(جهاز =>
            string.Equals(جهاز.الرقم_التسلسلي, قيمة, StringComparison.OrdinalIgnoreCase));
    }

    public void تغيير_حالة_الجهاز(string الرقم_التسلسلي, حالة_الصيانة الحالة_الجديدة)
    {
        جهاز_منزلي? الجهاز = البحث_عن_جهاز(الرقم_التسلسلي);
        if (الجهاز is null)
            throw new KeyNotFoundException("لم يتم العثور على جهاز بهذا الرقم التسلسلي.");

        الجهاز.تحديث_الحالة(الحالة_الجديدة);
    }

    public int مراجعة_الأجهزة_المتأخرة(DateTime تاريخ_اليوم)
    {
        int عدد_التغييرات = 0;

        foreach (جهاز_منزلي الجهاز in _الأجهزة)
        {
            bool لم_يسلم = الجهاز.الحالة != حالة_الصيانة.تم_التسليم;
            bool تجاوز_الموعد = الجهاز.تاريخ_التسليم_المتوقع.Date < تاريخ_اليوم.Date;

            if (لم_يسلم && تجاوز_الموعد && الجهاز.الحالة != حالة_الصيانة.متأخر)
            {
                الجهاز.تحديث_الحالة(حالة_الصيانة.متأخر);
                عدد_التغييرات++;
            }
        }

        return عدد_التغييرات;
    }

    private void عند_تغير_حالة_الصيانة(
        جهاز_منزلي الجهاز,
        حالة_الصيانة الحالة_السابقة,
        حالة_الصيانة الحالة_الجديدة,
        string الرسالة)
    {
        _ = الجهاز;
        _ = الحالة_السابقة;
        _ = الحالة_الجديدة;
        تنبيه_الصيانة?.Invoke(الرسالة);
    }
}
