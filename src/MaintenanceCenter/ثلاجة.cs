namespace مركز_صيانة_الأجهزة;

/// <summary>
/// يمثل جهاز ثلاجة قيد الصيانة.
/// تُحسب تكلفة إصلاحها بإضافة تكلفة أعمال نظام التبريد (الضاغط، الغاز، المكثف...)
/// إلى التكلفة الأساسية المشتركة بين جميع الأجهزة.
/// </summary>
/// <remarks>
/// الكلاس <c>sealed</c> لأنه لا يُتوقع اشتقاق أنواع أخرى منه؛
/// وإن احتجت لاحقًا لأنواع مثل ثلاجة بابين أو فريزر، أزل <c>sealed</c>.
/// </remarks>
public sealed class ثلاجة : جهاز_منزلي
{
    /// <summary>تكلفة أعمال نظام التبريد (قيمة غير سالبة، تم التحقق منها عند الإنشاء).</summary>
    private readonly decimal _تكلفة_نظام_التبريد;

    /// <summary>
    /// ينشئ سجل صيانة جديدًا لثلاجة.
    /// </summary>
    /// <param name="الرقم_التسلسلي">المعرّف الفريد للجهاز.</param>
    /// <param name="اسم_العميل">اسم صاحب الجهاز.</param>
    /// <param name="رقم_الهاتف">رقم التواصل مع العميل.</param>
    /// <param name="وصف_العطل">وصف مختصر للعطل كما أبلغ عنه العميل.</param>
    /// <param name="تكلفة_قطع_الغيار">تكلفة قطع الغيار العامة (غير نظام التبريد).</param>
    /// <param name="أجور_العمل">أجور الفني.</param>
    /// <param name="تكلفة_نظام_التبريد">تكلفة أعمال نظام التبريد، وتُضاف إلى التكلفة الأساسية.</param>
    /// <param name="تاريخ_الاستلام">تاريخ استلام الجهاز من العميل.</param>
    /// <param name="تاريخ_التسليم_المتوقع">الموعد المتوقع لتسليم الجهاز بعد الإصلاح.</param>
    /// <param name="الحالة_المبدئية">حالة الصيانة عند الإنشاء، والافتراضي <c>مستلم</c>.</param>
    /// <exception cref="ArgumentException">
    /// إذا كانت <paramref name="تكلفة_نظام_التبريد"/> غير صالحة (مثلًا سالبة)،
    /// حسب قواعد <c>مدقق_البيانات.تحقق_من_التكلفة</c>.
    /// </exception>
    public ثلاجة(
        string الرقم_التسلسلي, string اسم_العميل, string رقم_الهاتف, string وصف_العطل,
        decimal تكلفة_قطع_الغيار, decimal أجور_العمل, decimal تكلفة_نظام_التبريد,
        DateTime تاريخ_الاستلام, DateTime تاريخ_التسليم_المتوقع,
        حالة_الصيانة الحالة_المبدئية = حالة_الصيانة.مستلم)
        : base(الرقم_التسلسلي, اسم_العميل, رقم_الهاتف, وصف_العطل,
               تكلفة_قطع_الغيار, أجور_العمل, تاريخ_الاستلام, تاريخ_التسليم_المتوقع, الحالة_المبدئية)
    {
        // التحقق هنا (وليس في الكلاس الأب) لأن هذه القيمة خاصة بالثلاجة فقط.
        _تكلفة_نظام_التبريد = مدقق_البيانات.تحقق_من_التكلفة(تكلفة_نظام_التبريد, "تكلفة نظام التبريد");
    }

    /// <inheritdoc/>
    public override string نوع_الجهاز => "ثلاجة";

    /// <summary>تكلفة أعمال نظام التبريد (للقراءة فقط).</summary>
    public decimal تكلفة_نظام_التبريد => _تكلفة_نظام_التبريد;

    /// <inheritdoc/>
    /// <remarks>في الثلاجة، التكلفة الإضافية = تكلفة نظام التبريد.</remarks>
    public override decimal التكلفة_الإضافية => _تكلفة_نظام_التبريد;

    /// <summary>
    /// يحسب التكلفة النهائية للإصلاح: التكلفة الأساسية + تكلفة نظام التبريد،
    /// مقرّبة إلى خانتين عشريتين.
    /// </summary>
    /// <returns>إجمالي تكلفة الإصلاح.</returns>
    public override decimal حساب_تكلفة_الإصلاح() => decimal.Round(التكلفة_الأساسية + _تكلفة_نظام_التبريد, 2);
}