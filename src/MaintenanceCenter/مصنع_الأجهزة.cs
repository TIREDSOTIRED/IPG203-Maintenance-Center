namespace مركز_صيانة_الأجهزة;

/// <summary>
/// يحول بيانات JSON إلى كائن من الصنف الفرعي المناسب.
/// </summary>
public static class مصنع_الأجهزة
{
    public static جهاز_منزلي إنشاء(بيانات_جهاز بيانات)
    {
        ArgumentNullException.ThrowIfNull(بيانات);

        if (!Enum.TryParse(بيانات.الحالة, ignoreCase: false, out حالة_الصيانة الحالة) ||
            !Enum.IsDefined(typeof(حالة_الصيانة), الحالة))
            throw new InvalidDataException($"حالة الصيانة غير صالحة للجهاز {بيانات.الرقم_التسلسلي}.");

        return بيانات.نوع_الجهاز switch
        {
            "ثلاجة" => new ثلاجة(
                بيانات.الرقم_التسلسلي, بيانات.اسم_العميل, بيانات.رقم_الهاتف, بيانات.وصف_العطل,
                بيانات.تكلفة_قطع_الغيار, بيانات.أجور_العمل, بيانات.التكلفة_الإضافية,
                بيانات.تاريخ_الاستلام, بيانات.تاريخ_التسليم_المتوقع, الحالة),
            "غسالة" => new غسالة(
                بيانات.الرقم_التسلسلي, بيانات.اسم_العميل, بيانات.رقم_الهاتف, بيانات.وصف_العطل,
                بيانات.تكلفة_قطع_الغيار, بيانات.أجور_العمل, بيانات.التكلفة_الإضافية,
                بيانات.تاريخ_الاستلام, بيانات.تاريخ_التسليم_المتوقع, الحالة),
            "مكيف" => new مكيف(
                بيانات.الرقم_التسلسلي, بيانات.اسم_العميل, بيانات.رقم_الهاتف, بيانات.وصف_العطل,
                بيانات.تكلفة_قطع_الغيار, بيانات.أجور_العمل, بيانات.التكلفة_الإضافية,
                بيانات.تاريخ_الاستلام, بيانات.تاريخ_التسليم_المتوقع, الحالة),
            _ => throw new InvalidDataException($"نوع الجهاز «{بيانات.نوع_الجهاز}» غير مدعوم.")
        };
    }

    public static بيانات_جهاز تحويل_إلى_بيانات(جهاز_منزلي الجهاز)
    {
        return new بيانات_جهاز
        {
            نوع_الجهاز = الجهاز.نوع_الجهاز,
            الرقم_التسلسلي = الجهاز.الرقم_التسلسلي,
            اسم_العميل = الجهاز.اسم_العميل,
            رقم_الهاتف = الجهاز.رقم_الهاتف,
            وصف_العطل = الجهاز.وصف_العطل,
            تكلفة_قطع_الغيار = الجهاز.تكلفة_قطع_الغيار,
            أجور_العمل = الجهاز.أجور_العمل,
            التكلفة_الإضافية = الجهاز.التكلفة_الإضافية,
            تاريخ_الاستلام = الجهاز.تاريخ_الاستلام,
            تاريخ_التسليم_المتوقع = الجهاز.تاريخ_التسليم_المتوقع,
            الحالة = الجهاز.الحالة.ToString()
        };
    }
}
