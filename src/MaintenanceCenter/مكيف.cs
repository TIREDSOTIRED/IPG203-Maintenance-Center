namespace مركز_صيانة_الأجهزة;

/// <summary>
/// يمثل المكيف ويضيف تكلفة خدمة غاز التبريد إلى التكلفة الأساسية.
/// </summary>
public sealed class مكيف : جهاز_منزلي
{
    private readonly decimal _تكلفة_غاز_التبريد;

    public مكيف(
        string الرقم_التسلسلي, string اسم_العميل, string رقم_الهاتف, string وصف_العطل,
        decimal تكلفة_قطع_الغيار, decimal أجور_العمل, decimal تكلفة_غاز_التبريد,
        DateTime تاريخ_الاستلام, DateTime تاريخ_التسليم_المتوقع,
        حالة_الصيانة الحالة_المبدئية = حالة_الصيانة.مستلم)
        : base(الرقم_التسلسلي, اسم_العميل, رقم_الهاتف, وصف_العطل,
               تكلفة_قطع_الغيار, أجور_العمل, تاريخ_الاستلام, تاريخ_التسليم_المتوقع, الحالة_المبدئية)
    {
        _تكلفة_غاز_التبريد = مدقق_البيانات.تحقق_من_التكلفة(تكلفة_غاز_التبريد, "تكلفة غاز التبريد");
    }

    public override string نوع_الجهاز => "مكيف";
    public decimal تكلفة_غاز_التبريد => _تكلفة_غاز_التبريد;
    public override decimal التكلفة_الإضافية => _تكلفة_غاز_التبريد;
    public override decimal حساب_تكلفة_الإصلاح() => decimal.Round(التكلفة_الأساسية + _تكلفة_غاز_التبريد, 2);
}
